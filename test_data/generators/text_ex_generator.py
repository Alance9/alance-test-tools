    def generate(self, count=1):
        """生成指定数量的文本类数据"""
        data = []
        for _ in range(count):
            data.append({
                '中文句子': self.fake_zh.sentence(nb_words=8),
                '英文句子': self.fake_en.sentence(nb_words=10),
                'emoji': ''.join(random.choices(self.EMOJIS, k=random.randint(1, 5))),
                '特殊字符': ''.join(random.choices(self.SPECIAL_CHARS, k=random.randint(3, 10))),
            })
        return data

    def get_fields(self):
        """返回字段列表"""
        return ['中文句子', '英文句子', 'emoji', '特殊字符']
